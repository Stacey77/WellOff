export function getMovementScoreColor(score: number): string {
  if (score >= 61) return 'text-accent-green'
  if (score >= 31) return 'text-accent-amber'
  return 'text-accent-red'
}

export function getMovementScoreBg(score: number): string {
  if (score >= 61) return 'bg-green-500'
  if (score >= 31) return 'bg-amber-500'
  return 'bg-red-500'
}

export function formatCurrency(value: number): string {
  if (value >= 1000000) {
    return `$${(value / 1000000).toFixed(1)}M`
  }
  if (value >= 1000) {
    return `$${(value / 1000).toFixed(0)}K`
  }
  return `$${value}`
}
