export function getTerritoryStatusColor(status: Territory['status']): string {
  switch (status) {
    case 'claimed': return 'text-accent-green border-green-500/40 bg-green-500/10'
    case 'contested': return 'text-accent-amber border-amber-500/40 bg-amber-500/10'
    case 'available': return 'text-accent-cyan border-cyan-500/40 bg-cyan-500/10'
  }
}

export function getOpportunityColor(score: number): string {
  if (score >= 80) return 'text-accent-green'
  if (score >= 60) return 'text-accent-amber'
  return 'text-accent-red'
}
